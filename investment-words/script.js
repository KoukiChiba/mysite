function showDrawer(name) {
    const term = terms.find((item) => item.name === name);
    if (!term) return;

    document.querySelector("#drawerCategory").textContent = term.category;
    document.querySelector("#drawerTitle").textContent = term.name;
    document.querySelector("#drawerOneLine").textContent = term.oneLine;
    document.querySelector("#drawerExample").textContent = term.example;
    document.querySelector("#drawerCaution").textContent = term.caution;
    document.querySelector("#drawerMistake").textContent = term.mistake;
    document.querySelector("#drawerRelated").innerHTML = term.related.map((related) => `<span>${related}</span>`).join("");

    drawer.classList.add("open");
    drawer.setAttribute("aria-hidden", "false");
    closeDrawer.focus();
}

function hideDrawer() {
    drawer.classList.remove("open");
    drawer.setAttribute("aria-hidden", "true");
}

function renderQuiz() {
    const item = quizItems[state.quizIndex];
    state.answered = false;

    document.querySelector("#quizProgress").textContent = `${state.quizIndex + 1} / ${quizItems.length}`;
    document.querySelector("#quizQuestion").textContent = item.question;
    document.querySelector("#quizFeedback").textContent = "";
    document.querySelector("#nextQuestion").textContent = state.quizIndex === quizItems.length - 1 ? "結果を見る" : "次の問題へ";

    document.querySelector("#answerList").innerHTML = item.answers.map((answer, index) => `
        <button class="answer-btn" type="button" data-index="${index}">${answer}</button>
    `).join("");

    document.querySelectorAll(".answer-btn").forEach((button) => {
        button.addEventListener("click", () => answerQuiz(Number(button.dataset.index)));
    });
}

function answerQuiz(selectedIndex) {
    if (state.answered) return;

    const item = quizItems[state.quizIndex];
    const buttons = document.querySelectorAll(".answer-btn");
    state.answered = true;

    buttons.forEach((button, index) => {
        button.disabled = true;
        if (index === item.correct) {
            button.classList.add("correct");
        }
        if (index === selectedIndex && selectedIndex !== item.correct) {
            button.classList.add("wrong");
        }
    });

    if (selectedIndex === item.correct) {
        state.score += 1;
        document.querySelector("#quizFeedback").textContent = `正解です。${item.note}`;
    } else {
        document.querySelector("#quizFeedback").textContent = `不正解です。${item.note}`;
    }
}

function nextQuestion() {
    if (!state.answered) {
        document.querySelector("#quizFeedback").textContent = "先に回答を選んでください。";
        return;
    }

    if (state.quizIndex === quizItems.length - 1) {
        document.querySelector("#quizQuestion").textContent = `結果：${state.score} / ${quizItems.length} 問正解`;
        document.querySelector("#answerList").innerHTML = "";
        document.querySelector("#quizFeedback").textContent = state.score === quizItems.length
            ? "基本用語はかなり押さえられています。次は関連語も確認してみましょう。"
            : "間違えた用語はカードで注意点まで読み返すと理解が安定します。";
        document.querySelector("#nextQuestion").textContent = "もう一度挑戦";
        state.quizIndex = -1;
        state.answered = true;
        return;
    }

    if (state.quizIndex === -1) {
        restartQuiz();
        return;
    }

    state.quizIndex += 1;
    renderQuiz();
}

function restartQuiz() {
    state.quizIndex = 0;
    state.score = 0;
    renderQuiz();
}

