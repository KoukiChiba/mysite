function bindEvents() {
    searchInput.addEventListener("input", (event) => {
        state.query = event.target.value.trim().toLowerCase();
        renderTerms();
    });

    resetFilters.addEventListener("click", () => {
        state.category = "すべて";
        state.query = "";
        searchInput.value = "";
        renderCategories();
        renderTerms();
    });

    closeDrawer.addEventListener("click", hideDrawer);
    drawerBackdrop.addEventListener("click", hideDrawer);

    document.addEventListener("keydown", (event) => {
        if (event.key === "Escape") {
            hideDrawer();
        }
    });

    document.querySelector("#nextQuestion").addEventListener("click", nextQuestion);
    document.querySelector("#restartQuiz").addEventListener("click", restartQuiz);
}

function renderCategories() {
    categoryTabs.innerHTML = categories.map((category) => `
        <button class="filter-btn ${category === state.category ? "active" : ""}" type="button" data-category="${category}">
            ${category}
        </button>
    `).join("");

    categoryTabs.querySelectorAll("button").forEach((button) => {
        button.addEventListener("click", () => {
            state.category = button.dataset.category;
            renderCategories();
            renderTerms();
        });
    });
}

