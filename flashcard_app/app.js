const filterButtons  = document.querySelectorAll('.filter__btn');

// =============================================
// 関数: カードを表示する
// =============================================
function showCard() {
  if (currentCards.length === 0) {
    cardQuestion.textContent = '問題がありません';
    cardAnswer.textContent = '';
    cardAnswer.classList.remove('visible');
    progressText.textContent = '0 / 0';
    progressFill.style.width = '0%';
    return;
  }

  const card = currentCards[currentIndex];

  cardQuestion.textContent = card.q;
  cardSource.textContent   = card.source === 'TOEIC' ? 'TOEIC 金フレ' : 'ターゲット 1900';

  if (card.source === 'ターゲット1900') {
    cardSource.classList.add('card__source--target');
  } else {
    cardSource.classList.remove('card__source--target');
  }

  cardAnswer.textContent = '';
  cardAnswer.classList.remove('visible');
  isAnswerVisible = false;

  btnShowAnswer.style.display = 'block';
  btnNext.style.display = 'none';

  updateBookmarkButton(card);
  updateProgress();
}

// =============================================
// 関数: 進捗バーを更新する
// =============================================
function updateProgress() {
  const total = currentCards.length;
  const current = total > 0 ? currentIndex + 1 : 0;
  const percent = total > 0 ? (current / total) * 100 : 0;
  progressText.textContent = `${current} / ${total}`;
  progressFill.style.width = `${percent}%`;
}

// =============================================
// 関数: ブックマークボタンの表示を更新する
// =============================================
function updateBookmarkButton(card) {
  const isMarked = bookmarks.has(card.q);
  btnBookmark.textContent = isMarked ? '★' : '☆';
  btnBookmark.classList.toggle('card__bookmark--active', isMarked);
}

// =============================================
// イベント: ブックマークボタンのクリック
// =============================================
btnBookmark.addEventListener('click', () => {
  const card = currentCards[currentIndex];
  if (!card) return;

  if (bookmarks.has(card.q)) {
    bookmarks.delete(card.q);
    // ブックマークモード中に解除したら次のカードへ（またはリスト更新）
    if (isBookmarkMode) {
      currentCards = allCards.filter(c => bookmarks.has(c.q));
      if (currentCards.length === 0) {
        // ブックマークが空になったら全カードに戻す
        isBookmarkMode = false;
        filterButtons.forEach(b => {
          b.classList.toggle('filter__btn--active', b.dataset.source === 'all');
        });
        baseCards = [...allCards];
        currentCards = [...allCards];
        currentIndex = 0;
      } else {
        currentIndex = Math.min(currentIndex, currentCards.length - 1);
      }
      showCard();
    }
  } else {
    bookmarks.add(card.q);
  }
  saveBookmarks(bookmarks);
  updateBookmarkButton(currentCards[currentIndex]);
});

// =============================================
// 関数: 配列をシャッフルする（Fisher-Yates アルゴリズム）
// =============================================
function shuffleArray(array) {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// =============================================
// イベント: 「答えを見る」ボタンのクリック
// =============================================
btnShowAnswer.addEventListener('click', () => {
  if (isAnswerVisible) return;

  const card = currentCards[currentIndex];
  cardAnswer.textContent = card.a;
  cardAnswer.classList.add('visible');
  isAnswerVisible = true;

  btnShowAnswer.style.display = 'none';
  btnNext.style.display = 'block';
});

// =============================================
// イベント: 「次の問題へ」ボタンのクリック
// =============================================
btnNext.addEventListener('click', () => {
  if (currentIndex < currentCards.length - 1) {
    currentIndex++;
    showCard();
  } else if (isQuizMode) {
    // ランダム10問モード: 最後の問題が終わったら完了画面へ
    showQuizComplete();
  } else {
    currentIndex = 0;
    showCard();
  }
});

// =============================================
// イベント: 「シャッフル」ボタンのクリック
// =============================================
btnShuffle.addEventListener('click', () => {
  currentCards = shuffleArray(currentCards);
  currentIndex = 0;
  showCard();
});

// =============================================
// イベント: フィルターボタンのクリック
// =============================================
filterButtons.forEach(btn => {
  btn.addEventListener('click', () => {
    filterButtons.forEach(b => b.classList.remove('filter__btn--active'));
    btn.classList.add('filter__btn--active');

    const source = btn.dataset.source;

    isQuizMode = false;
    isBookmarkMode = false;

    if (source === 'all') {
      baseCards = [...allCards];
    } else if (source === 'bookmark') {
      isBookmarkMode = true;
      baseCards = allCards.filter(card => bookmarks.has(card.q));
    } else {
      baseCards = allCards.filter(card => card.source === source);
    }

    // クイズモードを解除して全カード表示に戻す
    currentCards = [...baseCards];
    currentIndex = 0;
    showCard();
    resetQuizButtons();
  });
});

// =============================================
// イベント: 「ランダム10問」ボタンのクリック
// =============================================
btnRandom.addEventListener('click', () => {
  startRandomQuiz(10);
});

// =============================================
// イベント: 「もう一度10問」ボタンのクリック
// =============================================
btnRetry.addEventListener('click', () => {
  startRandomQuiz(10);
});

// =============================================
// イベント: 「全問に戻る」ボタンのクリック
// =============================================
btnBack.addEventListener('click', () => {
  isQuizMode = false;
  currentCards = [...baseCards];
  currentIndex = 0;
  showCard();
  resetQuizButtons();
});

// =============================================
// 関数: ランダム10問を開始する
// =============================================
function startRandomQuiz(count) {
  const shuffled = shuffleArray(baseCards);
  currentCards = shuffled.slice(0, Math.min(count, shuffled.length));
  currentIndex = 0;
  isQuizMode = true;

  cardEl.classList.remove('card--complete');
  btnShowAnswer.style.display = 'block';
  btnNext.style.display = 'none';
  btnRandom.style.display = 'none';
  btnShuffle.style.display = 'none';
  btnBookmark.style.display = 'block';
  btnRetry.style.display = 'none';
  btnBack.style.display = 'none';

  showCard();
}

// =============================================
// 関数: クイズ完了画面を表示する
// =============================================
function showQuizComplete() {
  const total = currentCards.length;

  cardEl.classList.add('card--complete');
  cardSource.textContent = '完了';
  cardSource.classList.remove('card__source--target');
  cardQuestion.textContent = `${total}問クリア！`;

  cardAnswer.textContent = 'お疲れ様でした！';
  cardAnswer.classList.remove('visible');
  // アニメーションのリセット
  void cardAnswer.offsetWidth;
  cardAnswer.classList.add('visible');

  progressText.textContent = `${total} / ${total}`;
  progressFill.style.width = '100%';

  btnShowAnswer.style.display = 'none';
  btnNext.style.display = 'none';
  btnBookmark.style.display = 'none';
  btnRetry.style.display = 'block';
  btnBack.style.display = 'block';
}

// =============================================
// 関数: クイズモード用ボタンをリセットする
// =============================================
function resetQuizButtons() {
  cardEl.classList.remove('card--complete');
  btnRandom.style.display = 'block';
  btnShuffle.style.display = 'block';
  btnBookmark.style.display = 'block';
  btnRetry.style.display = 'none';
  btnBack.style.display = 'none';
}

// =============================================
// 初期表示: ページ読み込み時に最初のカードを表示
// =============================================
showCard();
